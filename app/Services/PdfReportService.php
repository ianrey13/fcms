    // ============================================================
    // RECONCILIATION
    // ============================================================
    public static function reconciliation(array $data, array $filters): string
    {
        $reconciliations = $data['reconciliations'] ?? [];
        $headers = ['TT Number', 'Vehicle', 'Driver', 'Amount Released', 'Estimated Fuel', 'Actual Fuel', 'Variance', 'Status'];
        $rows = [];
        $totalAmount = 0; $totalEstimated = 0; $totalActual = 0;

        foreach ($reconciliations as $r) {
            $amount = (float) ($r['amount_released'] ?? 0);
            $est = (float) ($r['estimated_fuel'] ?? 0);
            $act = (float) ($r['actual_fuel'] ?? 0);
            $var = (float) ($r['variance'] ?? 0);

            $totalAmount += $amount;
            $totalEstimated += $est;
            $totalActual += $act;

            $varColor = abs($var) > 2 ? 'text-danger' : 'text-success';

            $rows[] = [
                e($r['ticket_number'] ?? 'N/A'),
                e($r['plate_number'] ?? 'N/A'),
                e($r['driver_name'] ?? 'N/A'),
                '₱' . number_format($amount, 2),
                number_format($est, 2),
                number_format($act, 2),
                '<span class="' . $varColor . '">' . number_format($var, 2) . '</span>',
                e(ucfirst($r['status'] ?? 'pending')),
            ];
        }

        $totalRow = ['TOTAL', '', '', '₱' . number_format($totalAmount, 2), number_format($totalEstimated, 2), number_format($totalActual, 2), '', ''];
        $period = 'Period: ' . ($filters['start_date'] ?? 'N/A') . ' to ' . ($filters['end_date'] ?? 'N/A');
        return self::wrap('Trip and Fuel Reconciliation Report', self::table($headers, $rows, $totalRow), $period);
    }

    // ============================================================
    // DRIVER EFFICIENCY
    // ============================================================
    public static function driverEfficiency(array $data, array $filters): string
    {
        $drivers = $data['drivers'] ?? [];
        $headers = ['Rank', 'Driver', 'Assigned Vehicle', 'Total Trips', 'Distance (km)', 'Fuel Used (L)', 'Efficiency (km/L)'];
        $rows = [];
        $rank = 1;
        $totalTrips = 0; $totalDistance = 0; $totalFuel = 0;

        foreach ($drivers as $d) {
            $trips = (int) ($d['total_trips'] ?? 0);
            $dist = (float) ($d['total_distance_km'] ?? 0);
            $fuel = (float) ($d['total_fuel_used_liters'] ?? 0);
            $eff = (float) ($d['fuel_efficiency_kmpl'] ?? 0);

            $totalTrips += $trips;
            $totalDistance += $dist;
            $totalFuel += $fuel;

            $rows[] = [
                $rank++,
                e($d['driver_name'] ?? 'N/A'),
                e($d['assigned_vehicle'] ?? 'N/A'),
                $trips,
                number_format($dist, 2),
                number_format($fuel, 2),
                number_format($eff, 2),
            ];
        }

        $avgEff = $totalFuel > 0 ? $totalDistance / $totalFuel : 0;
        $totalRow = ['', 'TOTAL', '', $totalTrips, number_format($totalDistance, 2), number_format($totalFuel, 2), number_format($avgEff, 2)];

        $period = 'Period: ' . ($filters['start_date'] ?? 'N/A') . ' to ' . ($filters['end_date'] ?? 'N/A');
        return self::wrap('Driver Fuel Efficiency Report', self::table($headers, $rows, $totalRow), $period);
    }

