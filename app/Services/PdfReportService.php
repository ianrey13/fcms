    /**
     * Wrap content in the standard PDF shell.
     */
    private static function wrap(string $title, string $body, ?string $periodText = null): string
    {
        $period = $periodText ?? '';
        return '<!DOCTYPE html>
        <html>
        <head>
            <meta charset="utf-8">
            <title>' . e($title) . '</title>
            <style>' . self::baseCss() . '</style>
        </head>
        <body>
            <div class="header">
                <h1>' . e(strtoupper($title)) . '</h1>
                <p>LGU Laguindingan - Fuel Consumption Monitoring System</p>
                <p class="subtitle">Generated: ' . now()->format('F d, Y h:i A') . '</p>
                ' . ($period ? '<p style="font-size:8px;color:#64748b;margin-top:3px;">' . e($period) . '</p>' : '') . '
            </div>
            ' . $body . '
            <div class="footer">
                <p>This report is automatically generated by the FCMS System</p>
                <p>© ' . date('Y') . ' Laguindingan Municipality - Fuel Consumption Monitoring System</p>
            </div>
        </body>
        </html>';
    }

    /**
     * Render a data table.
     */
    private static function table(array $headers, array $rows, ?array $totalRow = null): string
    {
        $html = '<table><thead><tr>';
        foreach ($headers as $h) {
            $html .= '<th>' . e($h) . '</th>';
        }
        $html .= '</tr></thead><tbody>';

        if (empty($rows)) {
            $html .= '<tr><td colspan="' . count($headers) . '" class="empty">No data available</td></tr>';
        } else {
            foreach ($rows as $row) {
                $html .= '<tr>';
                foreach ($row as $cell) {
                    $html .= '<td>' . $cell . '</td>';
                }
                $html .= '</tr>';
            }

            if ($totalRow) {
                $html .= '<tr class="total-row">';
                foreach ($totalRow as $cell) {
                    $html .= '<td>' . $cell . '</td>';
                }
                $html .= '</tr>';
            }
        }

        $html .= '</tbody></table>';
        return $html;
    }

    // ============================================================
    // VEHICLE SUMMARY
    // ============================================================
    public static function vehicleSummary(array $data, array $filters): string
    {
        $headers = ['Vehicle', 'Plate No.', 'Total Trips', 'Total Fuel (L)', 'Total Amount (₱)', 'Avg Fuel/Trip (L)'];
        $rows = [];
        $totalTrips = 0; $totalLiters = 0; $totalCost = 0;

        foreach ($data as $v) {
            $trips = (int) ($v['trip_count'] ?? 0);
            $liters = (float) ($v['total_liters'] ?? 0);
            $cost = (float) ($v['total_cost'] ?? 0);
            $avg = $trips > 0 ? $liters / $trips : 0;

            $totalTrips += $trips;
            $totalLiters += $liters;
            $totalCost += $cost;

            $rows[] = [
                e($v['model'] ?? 'N/A'),
                e($v['plate_number'] ?? 'N/A'),
                $trips,
                number_format($liters, 2),
                '₱' . number_format($cost, 2),
                number_format($avg, 2),
            ];
        }

        $avgTotal = $totalTrips > 0 ? $totalLiters / $totalTrips : 0;
        $totalRow = ['TOTAL', '', $totalTrips, number_format($totalLiters, 2), '₱' . number_format($totalCost, 2), number_format($avgTotal, 2)];

        $period = 'Period: ' . ($filters['start_date'] ?? 'N/A') . ' to ' . ($filters['end_date'] ?? 'N/A');
        return self::wrap('Vehicle Fuel Consumption Summary', self::table($headers, $rows, $totalRow), $period);
    }

